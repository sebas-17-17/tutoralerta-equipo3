    private void construirInterfaz() {
        setTitle("TutorAlerta - Menú Principal");
        setDefaultCloseOperation(javax.swing.WindowConstants.EXIT_ON_CLOSE);
        setResizable(false);

        
        getContentPane().removeAll();
        getContentPane().setLayout(new BorderLayout());

        JPanel panelFondo = new JPanel(new BorderLayout(0, 20));
        panelFondo.setBackground(new Color(245, 247, 250));
        panelFondo.setBorder(BorderFactory.createEmptyBorder(30, 45, 35, 45));

        // Encabezado
        JPanel panelEncabezado = new JPanel(new GridLayout(2, 1, 0, 5));
        panelEncabezado.setOpaque(false);

        JLabel lblTitulo = new JLabel("TutorAlerta", SwingConstants.CENTER);
        lblTitulo.setFont(new Font("Segoe UI", Font.BOLD, 28));
        lblTitulo.setForeground(new Color(30, 64, 175));

        JLabel lblSubtitulo = new JLabel("Alerta Temprana de Riesgo Académico", SwingConstants.CENTER);
        lblSubtitulo.setFont(new Font("Segoe UI", Font.PLAIN, 13));
        lblSubtitulo.setForeground(new Color(100, 116, 139));

        panelEncabezado.add(lblTitulo);
        panelEncabezado.add(lblSubtitulo);

       
        JPanel panelBotones = new JPanel(new GridLayout(3, 1, 0, 14));
        panelBotones.setOpaque(false);

        btnEstudiantes = crearBoton("Registrar Estudiantes", new Color(37, 99, 235));
        btnAsistencia = crearBoton("Tomar Asistencia", new Color(13, 148, 136));
        btnNotas = crearBoton("Registrar Notas", new Color(79, 70, 229));

        panelBotones.add(btnEstudiantes);
        panelBotones.add(btnAsistencia);
        panelBotones.add(btnNotas);

        
        JLabel lblPie = new JLabel("Seleccione una opción para continuar", SwingConstants.CENTER);
        lblPie.setFont(new Font("Segoe UI", Font.ITALIC, 12));
        lblPie.setForeground(new Color(148, 163, 184));

        panelFondo.add(panelEncabezado, BorderLayout.NORTH);
        panelFondo.add(panelBotones, BorderLayout.CENTER);
        panelFondo.add(lblPie, BorderLayout.SOUTH);

        getContentPane().add(panelFondo, BorderLayout.CENTER);

        setSize(450, 390);
        setLocationRelativeTo(null); // Centra la ventana en pantalla
    }
    
    private JButton crearBoton(String texto, Color colorFondo) {
        JButton boton = new JButton(texto);
        boton.setFont(new Font("Segoe UI", Font.BOLD, 15));
        boton.setBackground(colorFondo);
        boton.setForeground(Color.WHITE);
        boton.setFocusPainted(false);
        boton.setCursor(new Cursor(Cursor.HAND_CURSOR));
        return boton;
    }
